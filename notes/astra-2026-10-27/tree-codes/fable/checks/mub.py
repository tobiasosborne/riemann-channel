#!/usr/bin/env python3
"""T2 of notes/astra-2026-10-27/tree-codes/lane-brief.md  (claude:fable-5.1, 2026-10-27).

Qudit vertex M = p Z_p + Z_p (a = 1, b = 0), M^perp = Z_p + p^{-1} Z_p = p^{-1} M.  C_M = functions on Z_p / p Z_p = C^p.
On C_M the operators W~(u, j/p) = psi(u j /(2p)) W(u, j/p) (u in Z/p, j in Z/p) are  omega^{u j / 2} Z^j X^u  with
X f(x) = f(x+1), Z f(x) = omega^x f(x), omega = e^{2 pi i / p}, 1/2 = the inverse of 2 mod p.
The p+1 self-dual lattices M c L c M^perp are the lines of M^perp/M = F_p^2:  L_inf = p Z_p + p^{-1} Z_p  and
L_c = M + Z_p (1, c/p), c in F_p.  Their codes inside C_M are one-dimensional, spanned by the +1 joint eigenvector b_L of
W~(L)|_{C_M}; the basis of C_M attached to L is {W~(lam) b_L : lam in M^perp / L}.
Prints: the stabiliser check, the within-basis Gram matrices, all cross-basis |<b,b'>|^2, and the identification with
the eigenbases of Z (computational) and of Z^c X (quadratic phases).
Run: python3 checks/mub.py
"""
import numpy as np, itertools

def ops(p):
    om = np.exp(2j*np.pi/p)
    X = np.zeros((p, p), complex); Z = np.zeros((p, p), complex)
    for x in range(p):
        X[x, (x+1) % p] = 1          # (X f)(x) = f(x+1)
        Z[x, x] = om**x
    half = pow(2, -1, p)
    def Wt(u, j):                    # W~(u, j/p) on C_M
        return om**((half*u*j) % p) * np.linalg.matrix_power(Z, j % p) @ np.linalg.matrix_power(X, u % p)
    return om, X, Z, Wt

for p in (3, 5, 7):
    print(f"\n==================== p = {p}: qudit vertex M = pZ_p + Z_p, C_M = functions on Z_p/pZ_p")
    om, X, Z, Wt = ops(p)
    # representation property on M^perp (projective with the symplectic phase), check: W~(l) W~(l') = om^{(u j' - u' j)/2} W~(l+l')
    half = pow(2, -1, p)
    ok = True
    for (u, j, u2, j2) in itertools.product(range(p), repeat=4):
        lhs = Wt(u, j) @ Wt(u2, j2)
        rhs = om**((half*(u*j2 - u2*j)) % p) * Wt(u+u2, j+j2)
        ok &= np.allclose(lhs, rhs)
    print(f"W~(l)W~(l') = psi(omega(l,l')/2) W~(l+l') on M^perp/M: {ok}")
    # the p+1 lines of M^perp/M and their lattices: generators of L/M inside M^perp/M
    lines = {"inf": (0, 1)}                 # L_inf: generated over M by (0, 1/p)
    for c in range(p):
        lines[f"c={c}"] = (1, c)            # L_c: generated over M by (1, c/p)
    bases = {}
    for name, (u, j) in lines.items():
        S = Wt(u, j)                        # the stabiliser of L inside C_M is generated by this (and W~(M) = 1 on C_M)
        # +1 eigenvector
        w, v = np.linalg.eig(S)
        idx = [i for i in range(p) if abs(w[i] - 1) < 1e-9]
        assert len(idx) == 1, (name, w)
        b = v[:, idx[0]]; b = b / np.linalg.norm(b)
        # normalise the phase so that the first nonzero entry is positive real
        k0 = np.argmax(abs(b) > 1e-9); b = b * abs(b[k0]) / b[k0]
        # the basis: W~(lam) b for lam in M^perp / L: complement generator
        comp = (1, 0) if name == "inf" else (0, 1)
        B = np.column_stack([Wt(comp[0]*m, comp[1]*m) @ b for m in range(p)])
        bases[name] = B
        G = B.conj().T @ B
        print(f"basis {name:5s}: stabiliser generator W~({u},{j}/p) = om^({half*u*j % p}) Z^{j} X^{u}; +1 vector b = "
              + np.array2string(b, precision=3, suppress_small=True, max_line_width=200)
              + f"; Gram = identity: {np.allclose(G, np.eye(p))}")
    names = list(bases)
    print("cross-basis |<b,b'>|^2 (min, max over all pairs of vectors in distinct bases):")
    allmin, allmax = 1, 0
    for a_, b_ in itertools.combinations(names, 2):
        ov = np.abs(bases[a_].conj().T @ bases[b_])**2
        allmin, allmax = min(allmin, ov.min()), max(allmax, ov.max())
    print(f"  over {len(names)} bases: min = {allmin:.12f}, max = {allmax:.12f}, 1/p = {1/p:.12f}; MUB: {abs(allmin-1/p) < 1e-9 and abs(allmax-1/p) < 1e-9}")
    # identification with the standard MUBs: basis inf = eigenbasis of Z (computational), basis c = eigenbasis of Z^c X
    Pm = np.abs(bases["inf"]); comp_ok = np.allclose(Pm @ Pm.T, np.eye(p)) and np.allclose(Pm.sum(0), 1) and np.allclose(Pm.max(0), 1)
    quad_ok = True
    for c in range(p):
        B = bases[f"c={c}"]
        # b_c(x) proportional to om^{-c x^2 / 2}: check the +1 vector against psi(-c x^2/(2p)) 1_{Z_p}
        target = np.array([om**((-half*c*x*x) % p) for x in range(p)]) / np.sqrt(p)
        col0 = B[:, 0]
        quad_ok &= abs(abs(np.vdot(target, col0)) - 1) < 1e-9
        # and the whole basis diagonalises Z^c X
        ZcX = np.linalg.matrix_power(Z, c) @ X
        D = B.conj().T @ ZcX @ B
        quad_ok &= np.allclose(D, np.diag(np.diag(D)))
    print(f"basis inf = computational basis up to order (eigenbasis of Z): {comp_ok}; basis c = quadratic phases psi(-c x^2/(2p)) 1_Z_p "
          f"shifted by Z^j, eigenbasis of Z^c X: {quad_ok}")
    # dual statement: 1_L (L = Z_p^2 = L_0) lies in the code of each index-p sublattice M' c L
    one = np.ones(p)/np.sqrt(p)   # 1_{Z_p} as a vector of C_M (support Z_p, constant mod p)
    print(f"1_{{Z_p}} in C_M for M = pZ_p + Z_p and fixed by W~(1,0) (=X) and W~(0,p)=1: {np.allclose(X @ one, one)}")
    # the brief's sign: with psi(-uv/2) the operator for lam = (1, c/p) is om^{-c/2} Z^c X, whose +1 eigenvector is the
    # translate psi(-c (x-1)^2/(2p)) (so the brief's convention gives a basis vector centred at x = 1, not 0)
    c = 1
    Sm = om**((-half*c) % p) * Z @ X
    w, v = np.linalg.eig(Sm)
    b = v[:, [i for i in range(p) if abs(w[i]-1) < 1e-9][0]]
    target0 = np.array([om**((-half*c*x*x) % p) for x in range(p)])
    target1 = np.array([om**((-half*c*(x-1)*(x-1)) % p) for x in range(p)])
    print(f"with the brief's sign psi(-uv/2): +1 vector of W~(1,1/p) is psi(-(x-1)^2/(2p)) [{abs(abs(np.vdot(target1,b))/np.linalg.norm(target1)/np.linalg.norm(b)-1)<1e-9}], "
          f"not psi(-x^2/(2p)) [{abs(abs(np.vdot(target0,b))/np.linalg.norm(target0)/np.linalg.norm(b)-1)<1e-9}]")
print("\nDONE")
