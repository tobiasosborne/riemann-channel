"""Checks and a figure for 'The tower of lattices' (notes/adelic-gkp/lattice-tower.md).

Setting. L = Z^{2n} with the standard symplectic form Omega (the stabiliser lattice of n GKP qunaught modes).
A step is an integer matrix M with M^T Omega M = q Omega; V = q M^{-1} is its Omega-adjoint, MV = VM = q.
For a graph with flux, M = [[0, -1], [q, A_s]] (graph-super.md).
Point tower: L_k = (1 - V^k) L; the code with stabiliser lattice L_k has dimension h_k = det(1 - M^k) and basis
W(e)|L>, e in Fix(M^k) = (1 - M^k)^{-1} L / L (the syndromes of period k).
Kernel tower: M^k L, of index q^{nk}.
"""
