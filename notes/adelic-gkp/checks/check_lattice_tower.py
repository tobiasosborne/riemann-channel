def check(name, ok, detail=""):
    global npass, nfail
    npass += bool(ok)
    nfail += (not ok)
    print(("PASS  " if ok else "FAIL  ") + name + ("  " + detail if detail else ""))


def obj(M):
    return np.array(M, dtype=object)

def mpow(M, k):
    P = np.eye(len(M), dtype=object)
    for _ in range(k):
        P = P.dot(M)
    return P

def omega(n):
    I, Z = np.eye(n, dtype=object), np.zeros((n, n), dtype=object)
    return np.block([[Z, I], [-I, Z]])

def step(As, q):
    n = len(As)
    I, Z = np.eye(n, dtype=object), np.zeros((n, n), dtype=object)
    return np.block([[Z, -I], [q * I, obj(As)]])

def det_int(M):
    return int(sp.Matrix(M.tolist()).det())

def invariants(M):
    S = smith_normal_form(sp.Matrix(M.tolist()), domain=sp.ZZ)
    return sorted(abs(int(S[i, i])) for i in range(len(M)) if abs(int(S[i, i])) != 1)

def frac_mod1(v):
    return tuple(Fraction(x) - (Fraction(x).numerator // Fraction(x).denominator) for x in v)

def periodic_points(M, k):
    """Fix(M^k) on R^{2n}/Z^{2n} as a list of tuples of Fractions (the group generated by the columns of (1-M^k)^{-1})"""
    C = sp.Matrix((np.eye(len(M), dtype=object) - mpow(M, k)).tolist())
    Ci = C.inv()
    gens = [frac_mod1([Fraction(int(sp.numer(Ci[i, j])), int(sp.denom(Ci[i, j]))) for i in range(len(M))]) for j in range(len(M))]
    zero = tuple(Fraction(0) for _ in range(len(M)))
    seen, frontier = {zero}, [zero]
    while frontier:
        new = []
        for e in frontier:
            for g in gens:
                f = frac_mod1([a + b for a, b in zip(e, g)])
                if f not in seen:
                    seen.add(f)
                    new.append(f)
        frontier = new
    return sorted(seen)

def act(M, e):
    return frac_mod1([sum(Fraction(int(M[i, j])) * e[j] for j in range(len(e))) for i in range(len(e))])

def pair(Om, lam, e):
    """Omega(lam, e) mod 1"""
    v = sum(Fraction(int(lam[i])) * Fraction(int(Om[i, j])) * e[j] for i in range(len(e)) for j in range(len(e)))
    return v - (v.numerator // v.denominator)


