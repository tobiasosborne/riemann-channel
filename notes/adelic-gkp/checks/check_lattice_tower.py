    p = sp.factorint(q)
    p = list(p.keys())[0]
    mu = np.linalg.eigvals(np.array(M, dtype=float))
    semis = sp.Poly(sp.gcd(cp.as_expr(), sp.diff(cp.as_expr(), x)), x).degree() == 0 or sp.Matrix(M.tolist()).is_diagonalizable()
    c1 = bool(np.allclose(np.abs(mu), np.sqrt(q))) and bool(semis)
    c3 = mid % p != 0
    print(f"      {name}: char poly coefficients {co}; (1) semisimple with |mu| = sqrt q: {c1}; (3) middle coefficient {mid} prime to {p}: {c3}; (4) V exists: True")
    if "hyperbolic" in name:
        check(f"{name}: not a Deligne module (condition 1 fails)", not c1)
    else:
        check(f"{name}: a Deligne module of rank {2 * n} over F_{q}", c1 and c3)

