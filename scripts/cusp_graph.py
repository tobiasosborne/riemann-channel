def ram_rh(TX, c):
    sd = spectrum_data(TX, c)
    lam = sd["triv_lam"]
    if len(lam) == 0:
        ram = True
    else:
        top = max(abs(x) for x in lam)
        ram = len(lam) <= 2 and all(abs(abs(x) - top) < 1e-8 for x in lam) and \
            (len(lam) == 1 or abs(lam[0] + lam[-1]) < 1e-8)
    res = sd["res"]
    mods = sorted(abs(z) for z in res)
    rh = len(res) <= 1 or (mods[-1] - mods[0]) < 1e-6   # 1e-6: multiple roots of p
    return ram, rh, res, mods, lam, sd


