# ---------------------------------------------------------------- the diagram Y
def build_T(TX, c, L):
    """T on core (indices 0..n-1, v_0 = 0) plus ray r_1..r_L (indices n..n+L-1)."""
    n = TX.shape[0]
    N = n + L
    T = np.zeros((N, N))
    T[:n, :n] = TX
    T[0, n] = c
    T[n, 0] = c
    for k in range(1, L):
        T[n + k - 1, n + k] = 1.0
        T[n + k, n + k - 1] = 1.0
    return T


def P0_of(n):
    P = np.zeros((n, n))
    P[0, 0] = 1.0
    return P


def poly_coeffs(matfun, deg):
    """Coefficients (low to high) of det matfun(z), a polynomial of degree <= deg,
    by evaluation at (deg+1)-th roots of unity and an inverse DFT."""
    N = deg + 1
    w = np.exp(2j * np.pi * np.arange(N) / N)
    vals = np.array([np.linalg.det(matfun(x)) for x in w])
    # vals[j] = sum_k a_k w^{jk}, so a = fft(vals)/N  (ifft would reverse the index)
    return np.fft.fft(vals) / N


def p_poly(TX, c):
    n = TX.shape[0]
    P0 = P0_of(n)
    I = np.eye(n)
    return poly_coeffs(lambda z: (1 + z * z) * I - z * TX - c * c * P0, 2 * n)


def pt_poly(TX, c):
    n = TX.shape[0]
    P0 = P0_of(n)
    I = np.eye(n)
    return poly_coeffs(lambda z: (1 + z * z) * I - z * TX - c * c * z * z * P0, 2 * n)


def polyroots(co, tol=1e-11):
    """Roots of sum_k co[k] z^k (co low-to-high), trimming negligible leading terms."""
    a = np.array(co, dtype=complex)
    scale = max(np.max(np.abs(a)), 1.0)
    k = len(a) - 1
    while k > 0 and abs(a[k]) < tol * scale:
        k -= 1
    if k == 0:
        return np.array([], dtype=complex)
    return np.roots(a[:k + 1][::-1])


def evalpoly(co, z):
    return sum(co[k] * z ** k for k in range(len(co)))


def common_split(rp, rpt, tol=1e-6):
    """Greedy multiset match of roots(p) against roots(ptilde)."""
    pool = list(rpt)
    common, rest = [], []
    for z in rp:
        best, bd = None, tol
        for i, w in enumerate(pool):
            d = abs(z - w)
            if d < bd:
                bd, best = d, i
        if best is None:
            rest.append(z)
        else:
            common.append(z)
            pool.pop(best)
    return common, rest


def cusp_forms(TX, tol=1e-9):
    """(lambda, psi) with T_X psi = lambda psi and psi(v_0) = 0."""
    n = TX.shape[0]
    w, V = np.linalg.eigh(TX)
    out = []
    i = 0
    while i < n:
        j = i
        while j + 1 < n and abs(w[j + 1] - w[i]) < 1e-9:
            j += 1
        blk = V[:, i:j + 1]
        row = blk[0, :].reshape(1, -1)
        if np.linalg.norm(row) < tol:
            for k in range(blk.shape[1]):
                out.append((w[i], blk[:, k]))
        else:
            Q = sla.null_space(row, rcond=1e-10)
            for k in range(Q.shape[1]):
                out.append((w[i], blk @ Q[:, k]))
        i = j + 1
    return out


def krylov(TX, tol=1e-9):
    """Orthonormal basis Q (first column e_{v_0}) of the Krylov space of T_X at v_0.
    Its orthocomplement is the largest T_X-invariant subspace inside v_0^perp, i.e.
    exactly the cusp forms, so p factorises as p_red * (cusp factors)."""
    n = TX.shape[0]
    Q = []
    w = np.zeros(n)
    w[0] = 1.0
    for _ in range(n):
        for _ in range(2):
            for q in Q:
                w = w - (q @ w) * q
        nw = np.linalg.norm(w)
        if nw < tol:
            break
        q = w / nw
        Q.append(q)
        w = TX @ q
    return np.array(Q).T


CIRC = 1e-6


def spectrum_data(TX, c):
    """Everything the polynomial picture gives: roots, resonances, trivial modes.
    Root finding is done on the Krylov block only, where no root is forced to be
    multiple by a cusp form; the cusp factors are deflated analytically."""
    n = TX.shape[0]
    Q = krylov(TX)
    TXk = Q.T @ TX @ Q
    dK = TXk.shape[0]
    pc_f, ptc_f = p_poly(TX, c), pt_poly(TX, c)
    pc, ptc = p_poly(TXk, c), pt_poly(TXk, c)
    rp = polyroots(pc)
    rpt = polyroots(ptc)
    edge = [z for z in rp if min(abs(z - 1), abs(z + 1)) < CIRC]
    circ = [z for z in rp if abs(abs(z) - 1) < CIRC and min(abs(z - 1), abs(z + 1)) >= CIRC]
    res = [z for z in rp if abs(z) < 1 - CIRC]
    out = [z for z in rp if abs(z) > 1 + CIRC]
    triv_nc = [1 / z for z in out]
    cf = cusp_forms(TX)
    cusp_roots = []
    triv_cusp = []
    for lam, _ in cf:
        zz = np.roots([1.0, -lam, 1.0])
        cusp_roots += list(zz)
        for z in zz:
            if abs(z) < 1 - CIRC:
                triv_cusp.append(z)
    triv_z = list(triv_nc) + triv_cusp
    triv_lam = sorted((z + 1 / z).real for z in triv_z)
    return dict(n=n, dK=dK, c=c, pc=pc_f.real, ptc=ptc_f.real, pc_red=pc.real,
                rp=list(rp) + cusp_roots, rp_red=list(rp), rpt=list(rpt),
                res=res, out=out, circ=circ, triv_z=triv_z, triv_nc=triv_nc,
                triv_lam=triv_lam, cusp=cf, cusp_roots=cusp_roots, n_edge=len(edge))


def R_closed(TX, c, z):
    """R from the exact rational form -p/ptilde."""
    return -evalpoly(p_poly(TX, c), z) / evalpoly(pt_poly(TX, c), z)


def R_direct(TX, c, z, L):
    """R by solving T g = lambda g on core + ray with g(r_k) = z^-k + R z^k imposed
    at the two outermost sites.  The ansatz solves the free ray recursion exactly,
    so this is an EXACT linear system, not a truncation: any L >= 3 gives the same R."""
    n = TX.shape[0]
    lam = z + 1 / z
    M = n + L + 1                      # unknowns: g_X (n), g(r_1..r_L), R
    A = np.zeros((M, M), dtype=complex)
    b = np.zeros(M, dtype=complex)
    r = 0
    for i in range(n):                 # core equations
        A[r, :n] = TX[i, :] - lam * np.eye(n)[i, :]
        if i == 0:
            A[r, n] += c
        r += 1
    A[r, n + 1] = 1.0                  # k = 1: g(r_2) + c g(v_0) - lam g(r_1) = 0
    A[r, 0] += c
    A[r, n] -= lam
    r += 1
    for k in range(2, L):              # k = 2..L-1
        A[r, n + k] = 1.0
        A[r, n + k - 2] = 1.0
        A[r, n + k - 1] = -lam
        r += 1
    for k in (L - 1, L):               # boundary fit
        A[r, n + k - 1] = 1.0
        A[r, M - 1] = -z ** k
        b[r] = z ** (-k)
        r += 1
    assert r == M
    x = np.linalg.solve(A, b)
    return x[M - 1], x


# ---------------------------------------------------------------- l^2 eigenvectors
def l2_eigvecs(TX, c, L):
    """Exact l^2 eigenvectors of T on the (truncated) Y: cusp forms extended by
    zero, and the trivial modes g_X = w, g(r_k) = c<v_0|w> z^k."""
    n = TX.shape[0]
    P0 = P0_of(n)
    out = []
    for lam, psi in cusp_forms(TX):
        g = np.concatenate([psi, np.zeros(L)])
        out.append((lam, g / np.linalg.norm(g)))
    for z in spectrum_data(TX, c)["triv_nc"]:
        if abs(z.imag) > 1e-8:
            continue
        zr = z.real
        lam = zr + 1 / zr
        ns = sla.null_space(lam * np.eye(n) - TX - c * c * zr * P0, rcond=1e-8)
        for k in range(ns.shape[1]):
            w = ns[:, k].real
            alpha = c * w[0]
            if abs(alpha) < 1e-9:
                continue               # a cusp form, already listed
            g = np.concatenate([w, alpha * zr ** np.arange(1, L + 1)])
            out.append((lam, g / np.linalg.norm(g)))
    return out


# ---------------------------------------------------------------- Lax-Phillips K, Z
def lp_pieces(TX, c, L):
    """T, the energy matrix E, the wave step W, and the D_+ / D_- generators."""
    n = TX.shape[0]
    N = n + L
    T = build_T(TX, c, L)
    I = np.eye(N)
    E = np.block([[I, -T / 2], [-T / 2, I]])
    Wm = np.block([[T, -I], [I, np.zeros((N, N))]])

    def bvec(j):                                  # outgoing generator
        g = np.zeros(2 * N)
        g[n + j - 1] = 1.0
        if j == 1:
            g[N + 0] = c
        else:
            g[N + n + j - 2] = 1.0
        return g

    def fvec(j):                                  # incoming generator
        g = np.zeros(2 * N)
        g[n + j - 1] = 1.0
        g[N + n + j] = 1.0
        return g

    return n, N, T, E, Wm, bvec, fvec


def K_compact(TX, c, M=8, L=200, jstart=2, with_eig=True, rtol=1e-8):
    """The compactly supported part of K: vectors on core + r_1..r_M that are
    E-orthogonal to D_+ = span{b_j, j >= jstart}, to D_- = span{f_j, j >= 1} and
    (optionally) to all l^2 eigen-data.  Generators beyond j = M+3 give zero rows."""
    n, N, T, E, Wm, bvec, fvec = lp_pieces(TX, c, L)
    m = n + M
    S = np.zeros((2 * N, 2 * m))
    S[:m, :m] = np.eye(m)
    S[N:N + m, m:] = np.eye(m)
    ES = E @ S
    rows = [bvec(j) @ ES for j in range(jstart, M + 5)]
    rows += [fvec(j) @ ES for j in range(1, M + 5)]
    if with_eig:
        for lam, psi in l2_eigvecs(TX, c, L):
            d = np.zeros(2 * N)
            d[:N] = psi
            rows.append(d @ ES)
            d = np.zeros(2 * N)
            d[N:] = psi
            rows.append(d @ ES)
    A = np.array(rows)
    s = np.linalg.svd(A, compute_uv=False)
    rank = int(np.sum(s > rtol * s[0]))
    return 2 * m - rank


def gram_model(zs):
    """The Sz.-Nagy--Foias functional model of a contraction with defect indices
    (1,1) and characteristic function the Blaschke product over the DISTINCT
    resonances zs: Gram G_nm = 1/(1 - conj(z_n) z_m), C k_n = z_n k_n, <j|k_n> = 1."""
    zs = np.array(zs, dtype=complex)
    d = len(zs)
    G = 1.0 / (1 - np.outer(zs.conj(), zs))
    ev, U = np.linalg.eigh(G)
    assert ev.min() > 1e-12, f"Gram matrix not positive definite: {ev}"
    Rh = U @ np.diag(np.sqrt(ev)) @ U.conj().T
    Ri = U @ np.diag(1 / np.sqrt(ev)) @ U.conj().T
    C = Rh @ np.diag(zs) @ Ri
    jj = Ri @ np.ones(d)
    return dict(d=d, z=zs, G=G, C=C, j=jj, V=Rh, cond=ev.max() / ev.min())


def char_fn(C, jj, w):
    """The scalar characteristic function of a contraction with defect one."""
    d = C.shape[0]
    dc = np.eye(d) - C.conj().T @ C
    dcs = np.eye(d) - C @ C.conj().T
    ev, U = np.linalg.eigh(dc)
    jh = U[:, -1]
    ev2, U2 = np.linalg.eigh(dcs)
    jh2 = U2[:, -1]
    a = -(jh2.conj() @ (C @ jh))
    b = w * np.sqrt(ev[-1] * ev2[-1]) * (
        jh2.conj() @ np.linalg.solve(np.eye(d) - w * C.conj().T, jh))
    return a + b


def blaschke(zs, w):
    out = 1.0 + 0.0j
    for z in zs:
        out *= (z - w) / (1 - np.conj(z) * w)
    return out


# ---------------------------------------------------------------- renewal channel
def superop(C, Om, jj):
    """E_Omega(rho) = C rho C^* + <j|rho|j> Omega, row-major vec."""
    J = np.outer(jj, jj.conj())
    return np.kron(C, C.conj()) + np.outer(Om.reshape(-1), J.T.reshape(-1))


def apply_E(C, Om, jj, rho):
    return C @ rho @ C.conj().T + (jj.conj() @ rho @ jj).real * Om


def stein(C, Om):
    """X = sum_{m>=0} C^m Omega C^*m, the exact renewal sum (Stein equation
    X - C X C^* = Omega); used instead of a truncated sum because resonances can
    sit very close to the unit circle."""
    X = sla.solve_discrete_lyapunov(C, Om)
    return 0.5 * (X + X.conj().T)


def mhat(C, Om, jj, u):
    """mhat(u) = sum_m m(m) u^m = u <j|(1 - u E_0)^-1 Omega|j>, computed exactly."""
    d = C.shape[0]
    E0 = np.kron(C, C.conj())
    X = np.linalg.solve(np.eye(d * d) - u * E0, Om.reshape(-1)).reshape(d, d)
    return u * (jj.conj() @ X @ jj)


def rand_density(d, gen):
    A = gen.normal(size=(d, d)) + 1j * gen.normal(size=(d, d))
    rho = A @ A.conj().T
    return rho / np.trace(rho).real


