def bip_core(n1, n2, gen):
    """A bipartite core (v_0 in the first part): T on Y is then bipartite, so its
    spectrum and its resonance set are symmetric under lambda -> -lambda, z -> -z."""
    n = n1 + n2
    A = np.zeros((n, n))
    Bm = np.round(gen.normal(size=(n1, n2)), 3)
    A[:n1, n1:] = Bm
    A[n1:, :n1] = Bm.T
    return A


